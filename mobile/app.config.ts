/**
 * Expo config as TypeScript so one codebase can produce three apps.
 *
 * `APP_VARIANT` selects the environment at build time. Bundle identifiers differ per variant
 * on purpose: development, preview and production installs must be able to coexist on one
 * device, or testers end up overwriting the build they were asked to verify.
 */
type Variant = 'development' | 'preview' | 'production';

const VARIANT = (process.env.APP_VARIANT as Variant | undefined) ?? 'development';

const NAME: Record<Variant, string> = {
  development: 'Pahad Pulse (Dev)',
  preview: 'Pahad Pulse (Preview)',
  production: 'Pahad Pulse',
};

const BUNDLE_SUFFIX: Record<Variant, string> = {
  development: '.dev',
  preview: '.preview',
  production: '',
};

const BASE_BUNDLE_ID = 'in.pahadpulse.app';

/** Accessible interface blue derived from the logo. Keep in step with `src/theme/tokens.ts`. */
const BRAND_BLUE = '#075E9C';

/**
 * A production binary must never silently inherit the localhost development defaults from
 * `src/config/env.ts`. EAS evaluates this file before bundling, so failing here prevents a
 * store build whose every request would be sent to the reader's own phone.
 */
function assertProductionUrl(name: string, value: string | undefined): void {
  if (VARIANT !== 'production') return;

  if (!value) {
    throw new Error(`${name} must be set in the EAS production environment.`);
  }

  const url = new URL(value);
  if (url.protocol !== 'https:' || ['localhost', '127.0.0.1', '::1'].includes(url.hostname)) {
    throw new Error(`${name} must be a public HTTPS URL for production builds.`);
  }
}

/**
 * The Expo SDK 57 prebuild template sets `ENABLE_USER_SCRIPT_SANDBOXING = YES`, but the
 * "Bundle React Native code and images" phase declares no output paths. A sandboxed phase may
 * only write declared outputs, so a Release archive bundles the JS and is then denied writing
 * `main.jsbundle` (EPERM). Debug skips bundling, which is why only archives fail.
 *
 * `/ios` is gitignored and regenerated by prebuild, so the override has to live here rather
 * than in the Xcode project. See `IOS_ARCHIVE_FIX_HANDOFF.md`.
 */
const withScriptSandboxingDisabled: ConfigPlugin = (config) =>
  withXcodeProject(config, (modConfig) => {
    const configurations: Record<string, unknown> =
      modConfig.modResults.pbxXCBuildConfigurationSection();

    for (const entry of Object.values(configurations)) {
      // The section also holds `<id>_comment` string entries alongside the real configurations.
      if (typeof entry !== 'object' || entry === null || !('buildSettings' in entry)) continue;
      const { buildSettings } = entry as { buildSettings: Record<string, unknown> };
      buildSettings.ENABLE_USER_SCRIPT_SANDBOXING = 'NO';
    }

    return modConfig;
  });

/**
 * UIScene lifecycle adoption, required from iOS/iPadOS 27.
 *
 * iOS 27 terminates any UIKit app that launches without a `UIApplicationSceneManifest`
 * (`_UIApplicationEvaluateRuntimeIssueForNoSceneLifecycleAdoption`, EXC_BREAKPOINT on launch).
 * App Review rejected 1.0.0 (1) for exactly this. The Expo SDK 57 template still creates the
 * window in `didFinishLaunchingWithOptions`, so the template is rewritten here: the app delegate
 * only builds the React Native factory, and a scene delegate owns the window and starts React.
 *
 * Under scenes UIKit no longer calls the app delegate's open-URL / user-activity methods, so
 * the scene delegate forwards deep links to `RCTLinkingManager`, and a cold-start link is passed
 * in as launch options so `Linking.getInitialURL()` still sees it.
 *
 * Anchors are asserted, not replaced best-effort, so a changed template fails at prebuild.
 */
const TEMPLATE_WINDOW_START = `#if os(iOS) || os(tvOS)
    window = UIWindow(frame: UIScreen.main.bounds)
    factory.startReactNative(
      withModuleName: "main",
      in: window,
      launchOptions: launchOptions)
#endif
`;

const SCENE_DELEGATE_SWIFT = `
// Added by withSceneLifecycle in app.config.ts — iOS 27 requires UIScene lifecycle adoption.
class SceneDelegate: UIResponder, UIWindowSceneDelegate {
  var window: UIWindow?

  func scene(
    _ scene: UIScene,
    willConnectTo session: UISceneSession,
    options connectionOptions: UIScene.ConnectionOptions
  ) {
    guard
      let windowScene = scene as? UIWindowScene,
      let appDelegate = UIApplication.shared.delegate as? AppDelegate,
      let factory = appDelegate.reactNativeFactory
    else { return }

    let window = UIWindow(windowScene: windowScene)
    self.window = window
    appDelegate.window = window

    // Rebuild the launch options React Native reads for Linking.getInitialURL().
    var launchOptions: [UIApplication.LaunchOptionsKey: Any] = [:]
    if let url = connectionOptions.urlContexts.first?.url {
      launchOptions[.url] = url
    }
    if let activity = connectionOptions.userActivities.first(where: {
      $0.activityType == NSUserActivityTypeBrowsingWeb
    }) {
      launchOptions[.userActivityDictionary] = [
        UIApplication.LaunchOptionsKey.userActivityType.rawValue: activity.activityType,
        "UIApplicationLaunchOptionsUserActivityKey": activity,
      ]
    }

    factory.startReactNative(withModuleName: "main", in: window, launchOptions: launchOptions)
  }

  func scene(_ scene: UIScene, openURLContexts URLContexts: Set<UIOpenURLContext>) {
    for context in URLContexts {
      _ = RCTLinkingManager.application(UIApplication.shared, open: context.url, options: [:])
    }
  }

  func scene(_ scene: UIScene, continue userActivity: NSUserActivity) {
    _ = RCTLinkingManager.application(
      UIApplication.shared, continue: userActivity, restorationHandler: { _ in })
  }
}
`;

const withSceneLifecycle: ConfigPlugin = (config) =>
  withAppDelegate(
    withInfoPlist(config, (modConfig) => {
      modConfig.modResults.UIApplicationSceneManifest = {
        UIApplicationSupportsMultipleScenes: false,
        UISceneConfigurations: {
          UIWindowSceneSessionRoleApplication: [
            {
              UISceneConfigurationName: 'Default Configuration',
              UISceneDelegateClassName: '$(PRODUCT_MODULE_NAME).SceneDelegate',
            },
          ],
        },
      };
      return modConfig;
    }),
    (modConfig) => {
      const appDelegate = modConfig.modResults;
      if (appDelegate.language !== 'swift') {
        throw new Error(`Expected a Swift AppDelegate, found ${appDelegate.language}.`);
      }
      // Already rewritten by a previous prebuild into the same directory: nothing to do.
      if (appDelegate.contents.includes('class SceneDelegate')) return modConfig;
      if (!appDelegate.contents.includes(TEMPLATE_WINDOW_START)) {
        throw new Error('Could not find the window setup in ios/PahadPulse/AppDelegate.swift.');
      }

      appDelegate.contents =
        appDelegate.contents.replace(
          TEMPLATE_WINDOW_START,
          '    // The window and React Native start in SceneDelegate (UIScene lifecycle).\n'
        ) + SCENE_DELEGATE_SWIFT;
      return modConfig;
    }
  );

/**
 * Release signing for the locally built Android bundle.
 *
 * The Expo template signs release builds with its bundled DEBUG keystore. Play rejects a
 * debug-signed upload outright, and the mistake is invisible until the Console refuses the
 * file, so the config is rewritten here rather than trusted to a hand edit — `/android` is
 * gitignored and regenerated by every prebuild.
 *
 * The keystore and its passwords are read from Gradle properties, which live in
 * `~/.gradle/gradle.properties`, OUTSIDE this repository. Nothing secret is committed (N8):
 *
 *   PAHADPULSE_UPLOAD_STORE_FILE=/Users/you/keys/pahadpulse-upload.jks
 *   PAHADPULSE_UPLOAD_STORE_PASSWORD=…
 *   PAHADPULSE_UPLOAD_KEY_ALIAS=upload
 *   PAHADPULSE_UPLOAD_KEY_PASSWORD=…
 *
 * With those unset, the release build fails with "Keystore file … not found" naming the
 * sentinel below. That failure is deliberate: a build that cannot be signed properly must
 * stop, never quietly fall back to the debug key.
 */
const RELEASE_SIGNING_CONFIG = `
        release {
            // Sentinel path: if this appears in a build error, the PAHADPULSE_UPLOAD_*
            // properties are missing from ~/.gradle/gradle.properties.
            storeFile file(findProperty('PAHADPULSE_UPLOAD_STORE_FILE') ?: 'UPLOAD_KEYSTORE_NOT_CONFIGURED.jks')
            storePassword findProperty('PAHADPULSE_UPLOAD_STORE_PASSWORD') ?: ''
            keyAlias findProperty('PAHADPULSE_UPLOAD_KEY_ALIAS') ?: ''
            keyPassword findProperty('PAHADPULSE_UPLOAD_KEY_PASSWORD') ?: ''
        }`;

const withAndroidReleaseSigning: ConfigPlugin = (config) =>
  withAppBuildGradle(config, (modConfig) => {
    const gradle = modConfig.modResults;
    if (gradle.language !== 'groovy') {
      throw new Error(`Expected a Groovy build.gradle, found ${gradle.language}.`);
    }

    const debugSigningBlock = `            keyPassword 'android'
        }`;
    const releaseUsesDebugKey = `        release {
            // Caution! In production, you need to generate your own keystore file.
            // see https://reactnative.dev/docs/signed-apk-android.
            signingConfig signingConfigs.debug`;

    /*
     * Both anchors are asserted rather than replaced best-effort. If a future Expo template
     * rewrites this file, the build must fail here — loudly, at prebuild — instead of
     * producing an unsigned or debug-signed bundle that is only rejected at upload.
     */
    if (!gradle.contents.includes(debugSigningBlock)) {
      throw new Error('Could not find the debug signingConfig in android/app/build.gradle.');
    }
    if (!gradle.contents.includes(releaseUsesDebugKey)) {
      // Already rewritten by a previous prebuild into the same directory: nothing to do.
      if (gradle.contents.includes('PAHADPULSE_UPLOAD_STORE_FILE')) return modConfig;
      throw new Error('Could not find the release buildType in android/app/build.gradle.');
    }

    gradle.contents = gradle.contents
      .replace(debugSigningBlock, `${debugSigningBlock}${RELEASE_SIGNING_CONFIG}`)
      .replace(
        releaseUsesDebugKey,
        `        release {
            signingConfig signingConfigs.release`
      );

    return modConfig;
  });

assertProductionUrl('EXPO_PUBLIC_API_URL', process.env.EXPO_PUBLIC_API_URL);
assertProductionUrl('EXPO_PUBLIC_WEB_URL', process.env.EXPO_PUBLIC_WEB_URL);

