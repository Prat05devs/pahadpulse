-- Nineteen years of statewide budget estimates, plus every comparable grant-wise table
-- published in the official Budget at a Glance archive (2018-19 onward).
--
-- All money is stored as thousand rupees. The summary pages print crore to two decimals;
-- multiplying by 10,000 preserves that published precision without floating-point storage.

UPDATE sources
   SET url = 'https://budget.uk.gov.in/budgets/',
       attribution = 'Source: Budget at a Glance archive, Budget Directorate, Government of Uttarakhand',
       may_redistribute = TRUE,
       metadata_status = 'provisional',
       metadata_note = 'Official annual Budget at a Glance documents, 2008-09 to 2026-27. Figures are budget estimates, not actual expenditure. State summaries are available for every archived year; comparable demand-wise tables begin in 2018-19. Displayed with prominent source acknowledgement and a direct link to each primary document.'
 WHERE source_key = 'uk-budget-directorate';

CREATE TABLE budget_year_summaries (
  fiscal_year         VARCHAR(9) PRIMARY KEY CHECK (fiscal_year ~ '^[0-9]{4}-[0-9]{2}$'),
  source_id           INTEGER NOT NULL REFERENCES sources(id) ON DELETE RESTRICT,
  revenue_receipts    BIGINT NOT NULL CHECK (revenue_receipts >= 0),
  capital_receipts    BIGINT NOT NULL CHECK (capital_receipts >= 0),
  total_receipts      BIGINT NOT NULL CHECK (
    total_receipts = revenue_receipts + capital_receipts
  ),
  revenue_expenditure BIGINT NOT NULL CHECK (revenue_expenditure >= 0),
  capital_expenditure BIGINT NOT NULL CHECK (capital_expenditure >= 0),
  total_expenditure   BIGINT NOT NULL CHECK (
    total_expenditure = revenue_expenditure + capital_expenditure
  ),
  document_url        TEXT NOT NULL CHECK (document_url ~ '^https://'),
  created_at          TIMESTAMP NOT NULL DEFAULT (now() AT TIME ZONE 'utc')
);

